import { describe, expect, it, vi } from "vitest";
import * as T from "three";
import { SceneSync } from "../../src/renderer/scene-sync";
import { createNestedMeshProject, createMaterialAnimationProject, emptyProject } from "../fixtures/projects";

const noAssets = () => undefined;
describe("domain scene synchronization", () => {
  it("updates and releases procedural roughness without changing geometry", () => {
    const project = createMaterialAnimationProject();
    const config = { kind: "grain" as const, seed: 1, scale: 4, intensity: .5, resolution: 128 as const };
    project.materials[0]!.proceduralMaps = { roughness: config };
    const sync = new SceneSync(() => {});
    sync.sync(project, noAssets);
    const mesh = sync.objects.get("mesh-node")!.content as T.Mesh;
    const geometry = mesh.geometry;
    const first = (mesh.material as T.MeshPhysicalMaterial).roughnessMap!;
    const disposed = vi.spyOn(first, "dispose");
    project.materials[0]!.proceduralMaps = { roughness: { ...config, seed: 2 } };
    sync.sync(project, noAssets);
    expect(mesh.geometry).toBe(geometry);
    expect((mesh.material as T.MeshPhysicalMaterial).roughnessMap).not.toBe(first);
    expect(disposed).toHaveBeenCalledOnce();
    delete project.materials[0]!.proceduralMaps;
    sync.sync(project, noAssets);
    expect((mesh.material as T.MeshPhysicalMaterial).roughnessMap).toBeNull();
    sync.dispose();
  });
  it("reports missing UV while retaining procedural settings", () => {
    const project = createMaterialAnimationProject();
    const node = project.nodes.find(item => item.id === "mesh-node")!;
    if (node.kind !== "mesh") throw new Error("fixture");
    node.meshSource = { kind: "editable", positions: [0, 0, 0, 1, 0, 0, 0, 1, 0], indices: [0, 1, 2] };
    project.materials[0]!.proceduralMaps = { roughness: { kind: "grain", seed: 1, scale: 4, intensity: .5, resolution: 128 } };
    const statuses: string[][] = [];
    const sync = new SceneSync(status => statuses.push(status.diagnostics));
    sync.sync(project, noAssets);
    expect(statuses.at(-1)?.some(message => message.includes("процедурная шероховатость не отображается"))).toBe(true);
    expect(((sync.objects.get("mesh-node")!.content as T.Mesh).material as T.MeshPhysicalMaterial).roughnessMap).toBeNull();
    expect(project.materials[0]!.proceduralMaps?.roughness).toBeDefined();
    sync.dispose();
  });
  it("shares a decoded baseColor map until its last mesh is removed", async () => {
    const project = createMaterialAnimationProject();
    const original = project.nodes.find(node => node.id === "mesh-node")!;
    const second = structuredClone(original);
    second.id = "second-mesh"; second.parentId = "nested-group";
    project.nodes.push(second); project.nodes.find(node => node.id === "nested-group")!.children.push(second.id);
    project.assets.push({ id: "image", hash: "a".repeat(64), mediaType: "image/png", path: "assets/image.png", colorSpace: "srgb" });
    project.materials[0]!.textureSlots = { baseColor: "image" };
    const close = vi.fn();
    const decode = vi.fn().mockResolvedValue({ width: 2, height: 2, close } as unknown as ImageBitmap);
    vi.stubGlobal("createImageBitmap", decode);
    try {
      const sync = new SceneSync(() => {});
      sync.sync(project, () => new Uint8Array([1]));
      await Promise.resolve(); await Promise.resolve();
      expect(decode).toHaveBeenCalledOnce();
      const firstMap = ((sync.objects.get("mesh-node")!.content as T.Mesh).material as T.MeshPhysicalMaterial).map;
      const secondMap = ((sync.objects.get("second-mesh")!.content as T.Mesh).material as T.MeshPhysicalMaterial).map;
      expect(firstMap).toBeInstanceOf(T.Texture);
      expect(secondMap).toBe(firstMap);
      const dispose = vi.spyOn(firstMap!, "dispose");
      project.nodes = project.nodes.filter(node => node.id !== "mesh-node");
      project.nodes.find(node => node.id === "nested-group")!.children = ["second-mesh"];
      sync.sync(project, () => new Uint8Array([1]));
      expect(dispose).not.toHaveBeenCalled();
      sync.dispose();
      expect(dispose).toHaveBeenCalledOnce(); expect(close).toHaveBeenCalledOnce();
    } finally { vi.unstubAllGlobals(); }
  });
  it("keeps a missing-UV assignment in the document and closes a late bitmap", async () => {
    const project = createMaterialAnimationProject();
    project.assets.push({ id: "image", hash: "a".repeat(64), mediaType: "image/png", path: "assets/image.png", colorSpace: "srgb" });
    project.materials[0]!.textureSlots = { baseColor: "image" };
    const mesh = project.nodes.find(node => node.id === "mesh-node")!;
    if (mesh.kind !== "mesh") throw new Error("fixture");
    mesh.meshSource = { kind: "editable", positions: [0, 0, 0, 1, 0, 0, 0, 1, 0], indices: [0, 1, 2] };
    const statuses: string[][] = [];
    const sync = new SceneSync(status => statuses.push(status.diagnostics));
    const decode = vi.fn(); vi.stubGlobal("createImageBitmap", decode);
    try {
      sync.sync(project, () => new Uint8Array([1]));
      expect(statuses.at(-1)?.some(message => message.includes("нет UV"))).toBe(true);
      expect(decode).not.toHaveBeenCalled();
      expect(project.materials[0]!.textureSlots?.baseColor).toBe("image");
      mesh.meshSource = { kind: "primitive", primitive: "cube", parameters: { size: 1 } };
      let resolve!: (bitmap: ImageBitmap) => void;
      decode.mockImplementation(() => new Promise<ImageBitmap>(r => { resolve = r; }));
      sync.sync(project, () => new Uint8Array([1]));
      sync.dispose();
      const close = vi.fn(); resolve({ width: 2, height: 2, close } as unknown as ImageBitmap);
      await Promise.resolve(); await Promise.resolve();
      expect(close).toHaveBeenCalledOnce();
    } finally { vi.unstubAllGlobals(); }
  });
  it("updates a shared PBR material without replacing geometry or mesh", () => {
    const project = createMaterialAnimationProject();
    const sync = new SceneSync(() => {});
    sync.sync(project, noAssets);
    const content = sync.objects.get("mesh-node")!.content as T.Mesh;
    const geometry = content.geometry;
    const old = content.material as T.MeshPhysicalMaterial;
    const disposed = vi.spyOn(old, "dispose");
    project.materials[0]!.roughness = 0.8;
    project.materials[0]!.baseColor = [0.1, 0.2, 0.3];
    sync.sync(project, noAssets);
    expect(sync.objects.get("mesh-node")!.content).toBe(content);
    expect(content.geometry).toBe(geometry);
    expect(disposed).toHaveBeenCalledOnce();
    expect((content.material as T.MeshPhysicalMaterial).roughness).toBe(0.8);
    expect((content.material as T.MeshPhysicalMaterial).color.toArray()).toEqual([0.1, 0.2, 0.3]);
    sync.dispose();
  });
  it("retains imported texture ownership while a domain override changes", async () => {
    const project = createMaterialAnimationProject();
    const mesh = project.nodes.find(node => node.id === "mesh-node")!;
    if (mesh.kind !== "mesh") throw new Error("fixture");
    mesh.meshSource = { kind: "asset", assetId: "glb" };
    project.assets.push({ id: "glb", hash: "f".repeat(64), path: `assets/${"f".repeat(64)}.glb`, mediaType: "model/gltf-binary", colorSpace: "none" });
    const texture = new T.Texture();
    const original = new T.MeshStandardMaterial({ map: texture });
    const disposedTexture = vi.spyOn(texture, "dispose");
    const disposedOriginal = vi.spyOn(original, "dispose");
    const sync = new SceneSync(() => {}, async () => new T.Mesh(new T.BoxGeometry(), original));
    sync.sync(project, () => new Uint8Array([1]));
    await Promise.resolve(); await Promise.resolve();
    project.materials[0]!.roughness = 0.9;
    sync.sync(project, () => new Uint8Array([1]));
    expect(disposedTexture).not.toHaveBeenCalled();
    expect(disposedOriginal).not.toHaveBeenCalled();
    sync.dispose();
    expect(disposedTexture).toHaveBeenCalledOnce();
    expect(disposedOriginal).toHaveBeenCalledOnce();
  });
  it("keeps wrapper and geometry identity while reparenting and reordering", () => {
    const project = createNestedMeshProject();
    const root = project.nodes[0]!;
    const group = project.nodes.find(node => node.id === "nested-group")!;
    const mesh = project.nodes.find(node => node.id === "mesh-node")!;
    const sync = new SceneSync(() => {});
    sync.sync(project, noAssets);
    const wrapper = sync.objects.get(mesh.id)!.object;
    const content = sync.objects.get(mesh.id)!.content;
    root.children = [mesh.id, group.id]; group.children = []; mesh.parentId = root.id;
    sync.sync(project, noAssets);
    expect(sync.objects.get(mesh.id)!.object).toBe(wrapper);
    expect(sync.objects.get(mesh.id)!.content).toBe(content);
    expect(wrapper.parent).toBe(sync.objects.get(root.id)!.object);
    expect(sync.objects.get(root.id)!.object.children.slice(0, 2)).toEqual([wrapper, sync.objects.get(group.id)!.object]);
    root.children = [group.id, mesh.id]; sync.sync(project, noAssets);
    expect(sync.objects.get(root.id)!.object.children.slice(0, 2)).toEqual([sync.objects.get(group.id)!.object, wrapper]);
    sync.dispose();
  });
  it("preserves stable objects and local hierarchy while transforms and visibility change", () => {
    const project = createNestedMeshProject();
    const states = [] as unknown[];
    const sync = new SceneSync(state => states.push(state));
    sync.sync(project, noAssets);
    const root = sync.objects.get(project.model.rootNodeId)!.object;
    const group = sync.objects.get("nested-group")!.object;
    const mesh = sync.objects.get("mesh-node")!.object;
    const originalContent = sync.objects.get("mesh-node")!.content;
    expect(group.parent).toBe(root);
    expect(mesh.parent).toBe(group);
    const node = project.nodes.find(n => n.id === "mesh-node")!;
    node.transform.position = [3, 2, 1]; node.visible = false;
    sync.sync(project, noAssets);
    expect(sync.objects.get("mesh-node")!.object).toBe(mesh);
    expect(sync.objects.get("mesh-node")!.content).toBe(originalContent);
    expect(mesh.position.toArray()).toEqual([3, 2, 1]);
    expect(mesh.visible).toBe(false);
    const oldGeometry = (originalContent as T.Mesh).geometry;
    const disposed = vi.spyOn(oldGeometry, "dispose");
    project.nodes = project.nodes.filter(n => n.id !== "mesh-node");
    project.nodes.find(n => n.id === "nested-group")!.children = [];
    sync.sync(project, noAssets);
    expect(disposed).toHaveBeenCalledOnce();
    expect(sync.objects.has("mesh-node")).toBe(false);
    sync.dispose();
  });
  it("clears old project and ignores late asset results after replacement", async () => {
    const project = createNestedMeshProject();
    const mesh = project.nodes.find(n => n.id === "mesh-node");
    if (!mesh || mesh.kind !== "mesh") throw new Error("fixture");
    mesh.meshSource = { kind: "asset", assetId: "a" };
    project.assets.push({ id: "a", hash: "f".repeat(64), mediaType: "model/gltf-binary", path: "assets/a.glb", colorSpace: "none" });
    let resolve!: (root: T.Object3D) => void;
    const pending = new Promise<T.Object3D>(r => { resolve = r; });
    const statuses = [] as { loading: number; diagnostics: string[] }[];
    const sync = new SceneSync(status => statuses.push(status), () => pending);
    const firstEpoch = {};
    sync.sync(project, () => new Uint8Array([1]), firstEpoch);
    expect(statuses.at(-1)?.loading).toBe(1);
    const oldObject = sync.objects.get("mesh-node")!.object;
    const replacement = structuredClone(emptyProject);
    replacement.id = project.id;
    sync.sync(replacement, noAssets, {});
    const geometry = new T.BoxGeometry();
    const disposed = vi.spyOn(geometry, "dispose");
    resolve(new T.Mesh(geometry, new T.MeshBasicMaterial()));
    await pending; await Promise.resolve();
    expect(disposed).toHaveBeenCalledOnce();
    expect(oldObject.parent).toBeNull();
    expect(sync.objects.has("mesh-node")).toBe(false);
    sync.dispose();
  });
  it("rejects invalid transforms without corrupting a valid world matrix", () => {
    const sync = new SceneSync(() => {});
    const project = createNestedMeshProject();
    sync.sync(project, noAssets);
    project.nodes.find(n => n.id === "nested-group")!.transform.position = [Infinity, 0, 0];
    expect(() => sync.sync(project, noAssets)).toThrow(/матрица/);
    sync.dispose();
  });
  it("preserves temporary navigation across document sync and restores project camera on replacement", () => {
    const sync = new SceneSync(() => {});
    const project = createNestedMeshProject();
    const epoch = {};
    sync.sync(project, noAssets, epoch);
    const version = sync.cameraVersion;
    sync.camera.position.set(20, 11, 7);
    project.nodes.find(n => n.id === "mesh-node")!.transform.position = [2, 0, 0];
    sync.sync(project, noAssets, epoch);
    expect(sync.camera.position.toArray()).toEqual([20, 11, 7]);
    expect(sync.cameraVersion).toBe(version);
    sync.sync(project, noAssets, {});
    expect(sync.camera.position.toArray()).toEqual(project.scene.camera.position);
    expect(sync.cameraVersion).toBe(version + 1);
    sync.dispose();
  });
});
